// gen_fixture.go — deterministic tick generator shared by all three targets.
// Seeded RNG so every framework replays byte-identical data.
package main

import (
	"encoding/json"
	"math"
	"math/rand"
	"os"
	"strconv"
	"strings"
)

type Tick struct {
	Row   int     `json:"row"`
	Price float64 `json:"price"`
	Size  float64 `json:"size"`
	Side  string  `json:"side"` // "bid" or "ask", for order-book ticks
}

func genSeries(seed int64, rows int, ticksPerRow int, worstCase bool) []Tick {
	r := rand.New(rand.NewSource(seed))
	base := make([]float64, rows)
	for i := range base {
		base[i] = 100 + float64(i)*3.7
	}
	var out []Tick
	totalTicks := rows * ticksPerRow
	for t := 0; t < totalTicks; t++ {
		if worstCase {
			// every row changes on this tick (resync/reconnect burst)
			for row := 0; row < rows; row++ {
				base[row] += (r.Float64() - 0.5) * 0.8
				out = append(out, Tick{
					Row:   row,
					Price: math.Round(base[row]*100) / 100,
					Size:  math.Round(r.Float64()*500*100) / 100,
					Side:  side(r),
				})
			}
		} else {
			// realistic: exactly one row changes per tick
			row := r.Intn(rows)
			base[row] += (r.Float64() - 0.5) * 0.8
			out = append(out, Tick{
				Row:   row,
				Price: math.Round(base[row]*100) / 100,
				Size:  math.Round(r.Float64()*500*100) / 100,
				Side:  side(r),
			})
		}
	}
	return out
}

func side(r *rand.Rand) string {
	if r.Float64() < 0.5 {
		return "bid"
	}
	return "ask"
}

func write(path string, ticks []Tick) {
	f, err := os.Create(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	enc := json.NewEncoder(f)
	if err := enc.Encode(ticks); err != nil {
		panic(err)
	}
}

func main() {
	os.MkdirAll("out", 0o755)
	sizes := []int{20, 500}
	if raw := os.Getenv("ROWS"); raw != "" {
		sizes = nil
		for _, part := range strings.Fields(raw) {
			n, err := strconv.Atoi(part)
			if err != nil || n <= 0 {
				panic("ROWS must contain positive integers")
			}
			sizes = append(sizes, n)
		}
	}
	for _, rows := range sizes {
		write_realistic := genSeries(42, rows, 200, false)
		// Keep the worst-case fixture bounded: one all-row burst is enough because
		// the sustained benchmark replays the fixture repeatedly. The previous
		// 40 bursts expanded to 10,000,000 Tick values for 500 rows and could
		// exhaust small CI/learning VMs during fixture generation.
		write_worst := genSeries(1337, rows, 1, true)
		write("out/ticks_realistic_"+strconv.Itoa(rows)+".json", write_realistic)
		write("out/ticks_worstcase_"+strconv.Itoa(rows)+".json", write_worst)
	}
}
EOF

