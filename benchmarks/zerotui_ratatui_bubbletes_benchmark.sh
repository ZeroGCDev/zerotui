#[derive(Serialize)]
struct StatSample {
    t: f64,
    ticks: usize,
    allocated_bytes: u64,
    alloc_count: u64,
}

#[derive(Serialize)]
struct SustainedResult {
    framework: String,
    rows: usize,
    density: String,
    ticks_per_sec: u64,
    samples: Vec<StatSample>,
}

fn run_sustained(args: &Args) {
    let ticks = load_fixture(&args.fixture);
    let mut app = App::new(args.rows);
    // Sustained runs execute under `script -qec`, giving stdout a real pty.
    // Use CrosstermBackend here so Ratatui follows the same terminal-output
    // path as the Go targets; TestBackend remains for Layer-1 only.
    use ratatui::backend::CrosstermBackend;
    let backend = CrosstermBackend::new(std::io::stdout());
    let mut terminal = Terminal::new(backend).unwrap();

    // HFT-style architecture: market ticks arrive at 1kHz into a queue;
    // rendering is independently capped at 60 FPS. Every frame drains all
    // queued logical ticks, then performs exactly one full Ratatui draw.
    let tick_interval = Duration::from_secs_f64(1.0 / args.tps as f64);
    let frame_interval = Duration::from_secs_f64(1.0 / 60.0);
    let deadline = Instant::now() + Duration::from_secs(args.duration_secs);
    let start = Instant::now();
    let mut last_sample = Instant::now();
    let mut samples = Vec::new();
    let mut queue: std::collections::VecDeque<()> = std::collections::VecDeque::with_capacity(65536);
    let mut next_tick = Instant::now();
    let mut next_frame = Instant::now();
    let mut idx = 0usize;
    let mut count = 0usize;
    let mut frame_count = 0usize;

    ALLOCATED.store(0, Ordering::Relaxed);
    ALLOC_COUNT.store(0, Ordering::Relaxed);

    while Instant::now() < deadline {
        let now = Instant::now();
        while now >= next_tick {
            queue.push_back(());
            next_tick += tick_interval;
        }

        if now >= next_frame {
            while queue.pop_front().is_some() {
                let batch = if args.density == "worst" { args.rows } else { 1 };
                for _ in 0..batch {
                    app.apply_tick(&ticks[idx % ticks.len()]);
                    idx += 1;
                }
                count += 1;
            }
            terminal.draw(|f| render::draw(f, &app)).unwrap();
            frame_count += 1;
            // Strict 60 FPS ceiling: never perform catch-up draws in a tight
            // loop after a slow frame. A late frame is simply late.
            next_frame = Instant::now() + frame_interval;
        }

        if last_sample.elapsed() >= Duration::from_secs(1) {
            last_sample = Instant::now();
            samples.push(StatSample {
                t: start.elapsed().as_secs_f64(),
                ticks: count,
                allocated_bytes: ALLOCATED.load(Ordering::Relaxed),
                alloc_count: ALLOC_COUNT.load(Ordering::Relaxed),
            });
        }
        let sleep_for = std::cmp::min(
            next_tick.saturating_duration_since(Instant::now()),
            next_frame.saturating_duration_since(Instant::now()),
        );
        if !sleep_for.is_zero() {
            std::thread::sleep(sleep_for);
        }
    }

    // Final drain is intentionally omitted: samples represent work completed
    // during the fixed wall-clock interval, not work queued after the deadline.
    let _ = frame_count;
    let result = SustainedResult {
        framework: "ratatui".into(),
        rows: args.rows,
        density: args.density.clone(),
        ticks_per_sec: args.tps,
        samples,
    };
    if let Ok(f) = File::create(&args.stats_out) {
        let _ = serde_json::to_writer(f, &result);
    }
}

fn run_interactive(args: &Args) {
    use crossterm::execute;
    use crossterm::terminal::{
        disable_raw_mode, enable_raw_mode, EnterAlternateScreen, LeaveAlternateScreen,
    };
    use ratatui::backend::CrosstermBackend;

    let ticks = load_fixture(&args.fixture);
    let mut app = App::new(args.rows);

    enable_raw_mode().unwrap();
    let mut stdout = std::io::stdout();
    execute!(stdout, EnterAlternateScreen).unwrap();
    let backend = CrosstermBackend::new(stdout);
    let mut terminal = Terminal::new(backend).unwrap();

    let interval = Duration::from_secs_f64(1.0 / args.tps as f64);
    let mut idx = 0usize;
    loop {
        let t = &ticks[idx % ticks.len()];
        idx += 1;
        app.apply_tick(t);
        terminal.draw(|f| render::draw(f, &app)).unwrap();

        if crossterm::event::poll(interval).unwrap() {
            if let crossterm::event::Event::Key(k) = crossterm::event::read().unwrap() {
                if k.code == crossterm::event::KeyCode::Char('q') {
                    break;
                }
            }
        }
    }

    disable_raw_mode().unwrap();
    execute!(terminal.backend_mut(), LeaveAlternateScreen).unwrap();
}

fn main() {
    let args = parse_args();
    if args.fixture.is_empty() {
        eprintln!("--fixture is required");
        std::process::exit(1);
    }
    if args.rows == 0 || (args.density != "realistic" && args.density != "worst") || args.tps == 0 || args.duration_secs == 0 {
        eprintln!("invalid benchmark arguments: rows>0, density=realistic|worst, duration>0, tps>0");
        std::process::exit(2);
    }
    if args.sustained {
        run_sustained(&args);
    } else {
        run_interactive(&args);
    }
}
