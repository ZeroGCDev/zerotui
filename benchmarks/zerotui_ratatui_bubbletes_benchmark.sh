                eprintln!("invalid --rows value");
                std::process::exit(2);
            }),
            "--density" => a.density = next_value(&mut i),
            "--duration" => a.duration_secs = next_value(&mut i).parse().unwrap_or_else(|_| {
                eprintln!("invalid --duration value");
                std::process::exit(2);
            }),
            "--fixture" => a.fixture = next_value(&mut i),
            "--sustained" => a.sustained = true,
            "--tps" => a.tps = next_value(&mut i).parse().unwrap_or_else(|_| {
                eprintln!("invalid --tps value");
                std::process::exit(2);
            }),
