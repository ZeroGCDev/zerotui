func loadFixture(path string) []Tick {
	f, err := os.Open(path)
	if err != nil {
		log.Fatalf("fixture: %v", err)
	}
	defer f.Close()
	var ticks []Tick
	if err := json.NewDecoder(f).Decode(&ticks); err != nil {
		log.Fatalf("fixture decode: %v", err)
	}
	return ticks
}

// positionsData backs the positions VirtualTable. Coarse-grained mutex is
// deliberate for a benchmark harness: see ZeroTUI docs, "Your own data /
// You are responsible for synchronization".
type positionsData struct {
	mu   sync.RWMutex
	rows [][3]string // symbol, price, pnl
}

func (p *positionsData) Cell(row, col int) string {
	p.mu.RLock()
	defer p.mu.RUnlock()
	if row >= len(p.rows) {
		return ""
	}
	return p.rows[row][col]
}

func (p *positionsData) Set(row int, price, pnl string) {
	p.mu.Lock()
	p.rows[row][1] = price
	p.rows[row][2] = pnl
	p.mu.Unlock()
}

func main() {
	rows := flag.Int("rows", 20, "positions table size")
	density := flag.String("density", "realistic", "realistic|worst")
	duration := flag.Int("duration", 30, "sustained run duration seconds")
	fixturePath := flag.String("fixture", "", "path to tick fixture JSON")
	sustained := flag.Bool("sustained", false, "run headless sustained-load benchmark instead of interactive UI")
	ticksPerSec := flag.Int("tps", 1000, "ticks per second to replay")
	statsOut := flag.String("stats-out", "/results/zerotui_sustained.json", "where to write sustained-run stats")
	flag.Parse()

	if *fixturePath == "" {
		log.Fatal("--fixture is required")
	}
	if *rows <= 0 || (*density != "realistic" && *density != "worst") || *ticksPerSec <= 0 || *duration <= 0 {
		log.Fatal("invalid benchmark arguments: rows>0, density=realistic|worst, duration>0, tps>0")
	}
	ticks := loadFixture(*fixturePath)

	// ---- build the 27-widget dashboard --------------------------------
