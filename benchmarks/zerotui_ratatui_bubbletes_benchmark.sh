	tickersPanel := layout.NewFlex(layout.Vertical, tickerNodes...)

	book := widget.NewOrderBook(2, 2, 2)
	bids := make([]widget.Level, 8)
	asks := make([]widget.Level, 8)
	for i := range bids {
		bids[i] = widget.Level{Price: uint64((10000 - i*2) * 100), Size: uint64((100 + i*10) * 100)}
		asks[i] = widget.Level{Price: uint64((10002 + i*2) * 100), Size: uint64((100 + i*8) * 100)}
	}
	book.SetLevels(bids, asks)

	posData := &positionsData{rows: make([][3]string, *rows)}
	for i := range posData.rows {
		posData.rows[i] = [3]string{fmt.Sprintf("SYM-%04d", i), "0.00", "+0.00"}
	}
	posCols := []widget.Column{
		{Title: "SYMBOL", Width: 12},
		{Title: "PRICE", Width: 12, Align: widget.AlignRight},
		{Title: "PNL", Width: 12, Align: widget.AlignRight},
	}
	posTable := widget.NewVirtualTable(posCols, *rows, posData.Cell)
	posTable.ShowScrollBar = true

	orderCols := []widget.Column{
		{Title: "ID", Width: 8},
		{Title: "SYMBOL", Width: 12},
		{Title: "SIDE", Width: 6},
		{Title: "STATUS", Width: 10},
	}
	orderTable := widget.NewTable(orderCols)
	orderTable.Rows = make([][]string, 20)
	for i := range orderTable.Rows {
		orderTable.Rows[i] = []string{fmt.Sprintf("%06d", i), symbols[i%len(symbols)], "BUY", "PENDING"}
	}
	orderTable.Zebra = true

	priceSpark := widget.NewSparkline(120)
	pnlSpark := widget.NewSparkline(120)
	for i := 0; i < 40; i++ {
		priceSpark.Push(100 + float64(i%10))
		pnlSpark.Push(float64(i % 5))
	}

	marginGauge := widget.NewGauge("MARGIN")
	marginGauge.Value = 0.35
	marginGauge.WarnAt = 0.70
	marginGauge.DangerAt = 0.90
	riskGauge := widget.NewGauge("RISK")
