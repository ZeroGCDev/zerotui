# zerotui_ratatui_bubbletes_benchmark.sh — fair HFT sustained + headless harness
#
# ZeroTUI vs Bubble Tea v2 + Lip Gloss v2 vs Ratatui — HFT dashboard stress test
#
# What this does, fully automatically:
#   1. Verifies/uses Podman (does NOT try to silently install a container
#      engine with root privileges on your behalf — see PREFLIGHT below).
#   2. Generates three ~25-widget "HFT trading terminal" dashboards:
#        - ZeroTUI          (Go, retained-mode)      -- real API, from
#                             github.com/ZeroGCDev/zerotui README as of
#                             the run date.
#        - Bubble Tea v2 + Lip Gloss v2 (Go, Elm-style, Cursed Renderer)
#        - Ratatui          (Rust, immediate-mode, double-buffer diff)
#   3. Generates ONE deterministic tick fixture (seeded RNG) shared by
#      all three, at two densities: "realistic" (1 row/tick) and
#      "worst case" (all rows/tick).
#   4. Builds a Podman image with the *latest* Go and *latest* stable Rust
#      toolchains pulled at build time (no pinned versions baked in), and
#      pulls the *latest* tagged versions of zerotui, bubbletea/v2,
#      lipgloss/v2, bubbles/v2, ratatui, crossterm, and criterion.
#   5. Runs the container with --cpus=4 --memory=2g (podman-native cgroup
#      limits — this is the actual stress-test constraint, not a VM).
#   6. Inside the container:
#        Layer 1 - headless state-mutation vs render costs for ALL THREE
#                    frameworks. ZeroTUI uses its public buffer/widget/layout
#                    renderer path; Bubble Tea separates model mutation from
#                    View construction; Ratatui uses TestBackend.
#        Layer 2 - fair sustained HFT load: 1kHz tick ingestion target +
#                    strict 60 FPS render ceiling for all three frameworks.
#                    Ticks are queued/batched; no framework is charged a
#                    terminal redraw once per market tick.
#        Layer 3 - real-pty terminal-output path is used by the sustained run
#                    for ALL THREE frameworks with identical pty geometry.
#      at dashboard sizes of 20 and 500 table rows, for both tick densities.
#      The sustained layer itself is the real-pty comparison; all three
#      binaries are launched through `script -qec` at the same terminal size.
#   7. Copies all raw results + a generated Markdown comparison table back
#      to ./tui-bench-results/ on the host.
#
# Usage:
#   chmod +x zerotui_ratatui_bubbletes_benchmark.sh
#   ./zerotui_ratatui_bubbletes_benchmark.sh
#
# Optional env overrides:
#   CPUS=4 MEM=2g ROWS="20 500" DENSITIES="1 all" DURATION=30 \
