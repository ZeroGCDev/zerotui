		layout.Fix(layout.Wrap(tabs), 1),
		layout.Fix(layout.Wrap(riskBar), 1),
		layout.Fix(layout.Wrap(eventLog), 6),
		layout.Fix(layout.Wrap(status), 1),
	)

	a := app.New(root, theme)
	a.TargetFPS = 60

	// ---- tick feeder ----------------------------------------------------
	stopCh := make(chan struct{})
	statsCh := make(chan statSample, 1024)
	var statsWG sync.WaitGroup

	go func() {
		interval := time.Second / time.Duration(*ticksPerSec)
		if interval <= 0 {
			interval = time.Millisecond
		}
		ticker := time.NewTicker(interval)
		defer ticker.Stop()

		start := time.Now()
		deadline := start.Add(time.Duration(*duration) * time.Second)
		count := 0
		idx := 0
		var lastSample time.Time
		for {
			select {
			case <-ticker.C:
				logicalUpdates := 1
				if *density == "worst" {
					logicalUpdates = *rows
				}
				count++
				a.BeginBatch()
				for j := 0; j < logicalUpdates; j++ {
					t := ticks[idx%len(ticks)]
					idx++
					if t.Row < len(prices) {
						atomic.StoreUint64(&prices[t.Row%len(prices)], uint64(t.Price*100))
						a.InvalidateWidgets(tickerRow[t.Row%len(tickerRow)])
					}
					if *rows > 0 {
						r := t.Row % *rows
						posData.Set(r, fmt.Sprintf("%.2f", t.Price), fmt.Sprintf("%+.2f", t.Price-100))
						a.InvalidateWidgets(posTable)
					}
					priceSpark.Push(t.Price)
					pnlSpark.Push(t.Price - 100)
					a.InvalidateWidgets(priceSpark, pnlSpark)
				}
				a.EndBatch()

				if *sustained && time.Since(lastSample) >= time.Second {
					lastSample = time.Now()
					var m runtime.MemStats
					runtime.ReadMemStats(&m)
					statsCh <- statSample{
						T:          time.Since(start).Seconds(),
						Ticks:      count,
						TotalAlloc: m.TotalAlloc,
						NumGC:      m.NumGC,
						PauseTotal: m.PauseTotalNs,
						HeapAlloc:  m.HeapAlloc,
					}
				}

				if *sustained && time.Now().After(deadline) {
					close(stopCh)
					return
				}
			case <-stopCh:
				return
			}
		}
	}()

	if *sustained {
		// Drain stats and write JSON, then hard-exit (this is a headless
		// stress run under `script`'s pty; no interactive quit key needed).
		var samples []statSample
		statsWG.Add(1)
		go func() {
			defer statsWG.Done()
			for s := range statsCh {
				samples = append(samples, s)
			}
		}()
		go func() {
			a.Run() // still exercises the real renderer/pty path
		}()
		<-stopCh
		time.Sleep(200 * time.Millisecond) // let last stats drain
		close(statsCh)
		statsWG.Wait()

		out := sustainedResult{
			Framework:   "zerotui",
			Rows:        *rows,
			Density:     *density,
			TicksPerSec: *ticksPerSec,
			Samples:     samples,
		}
		f, err := os.Create(*statsOut)
		if err == nil {
			json.NewEncoder(f).Encode(out)
			f.Close()
		}
		return
	}

	if err := a.Run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type statSample struct {
	T          float64 `json:"t"`
	Ticks      int     `json:"ticks"`
