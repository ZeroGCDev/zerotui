func (z *ztBench) applyTick(i int) {
    z.price += uint64(i&7)+1
    z.bids[i%len(z.bids)].Size++
    z.book.SetLevels(z.bids, z.asks)
    z.spark.Push(float64(z.price % 10000))
    z.app.InvalidateWidgets(z.ticker, z.spark, z.book)
}

