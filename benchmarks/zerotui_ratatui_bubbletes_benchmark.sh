      pause_ms=$(awk -v p1="$pause_last" -v p0="$pause_first" 'BEGIN{ printf "%.2f", (p1-p0)/1e6 }')
      gc_cycles=$(( gc_last - gc_first ))
      echo "| $fw | $rows | $density | $((ticks_last-ticks_first)) | $tps_eff | $alloc_rate | $gc_cycles | $pause_ms |" >> "${SUMMARY_MD}"
