find_target_pid() { # $1=launcher pid; returns deepest live descendant
  local root="$1" current="$1" child
  while true; do
    child="$(pgrep -P "$current" | tail -n1 || true)"
    [[ -n "$child" ]] || break
    current="$child"
  done
  echo "$current"
}

sample_rss() { # $1=launcher pid $2=outfile $3=seconds
  local launcher="$1" out="$2" secs="$3" pid
  : > "$out"
  for ((i=0; i<secs; i++)); do
    pid="$(find_target_pid "$launcher")"
    if [[ -r "/proc/$pid/status" ]]; then
      awk -v t="$i" '/VmRSS/{print t","$2}' "/proc/$pid/status" >> "$out" || true
    fi
    sleep 1
  done
}

