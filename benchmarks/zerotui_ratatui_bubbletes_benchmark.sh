fn parse_args() -> Args {
    let mut a = Args {
        rows: 20,
        density: "realistic".into(),
        duration_secs: 30,
        fixture: String::new(),
        sustained: false,
        tps: 1000,
        stats_out: "/results/ratatui_sustained.json".into(),
