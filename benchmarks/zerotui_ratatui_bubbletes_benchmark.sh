func (m *dashboardModel) startProducer() {
	if m.started || !m.sustained {
		return
	}
	m.started = true
	interval := time.Second / time.Duration(m.ticksPerSec)
	go func() {
		ticker := time.NewTicker(interval)
		defer ticker.Stop()
		deadline := time.Now().Add(m.duration)
		for {
			select {
			case <-ticker.C:
				// The fixture represents one logical market tick. Worst-case
				// expands that logical tick into rows state mutations in Update.
				select {
				case m.tickCh <- struct{}{}:
				case <-m.doneCh:
					return
				}
				if time.Now().After(deadline) {
					return
				}
			case <-m.doneCh:
				return
			}
		}
	}()
}

func nextFrameCmd() tea.Cmd {
	return tea.Tick(time.Second/60, func(time.Time) tea.Msg { return frameMsg{} })
}

func (m dashboardModel) Init() tea.Cmd {
	if m.sustained {
		m.startProducer()
	}
	return nextFrameCmd()
}

func (m *dashboardModel) applyTick(t Tick) {
    if t.Row < len(m.prices) { m.prices[t.Row] = t.Price }
    m.priceSpark = append(m.priceSpark, t.Price)
    if len(m.priceSpark) > 120 { m.priceSpark = m.priceSpark[len(m.priceSpark)-120:] }
    pnl := t.Price - 100
    m.pnlSpark = append(m.pnlSpark, pnl)
    if len(m.pnlSpark) > 120 { m.pnlSpark = m.pnlSpark[len(m.pnlSpark)-120:] }
    if m.rows > 0 { r:=t.Row%m.rows; m.positions[r].price=fmt.Sprintf("%.2f",t.Price); m.positions[r].pnl=fmt.Sprintf("%+.2f",pnl) }
    m.totalPnL += pnl/1000
    m.tickCount++
}

func (m dashboardModel) Update(msg tea.Msg) (tea.Model, tea.Cmd) {
	switch msg := msg.(type) {
	case tea.KeyMsg:
		if msg.String() == "q" || msg.String() == "ctrl+c" {
			if m.doneCh != nil {
				select { case <-m.doneCh: default: close(m.doneCh) }
			}
			return m, tea.Quit
		}
	case frameMsg:
		processed := 0
		for {
			select {
			case <-m.tickCh:
				batch := 1
				if m.density == "worst" { batch = m.rows }
				// Apply one queued logical tick. In worst-case mode the logical tick
				// contains rows consecutive fixture updates, matching ZeroTUI/Ratatui.
				for j := 0; j < batch; j++ {
					t := m.ticks[m.tickIdx%len(m.ticks)]
					m.tickIdx++
					m.applyTick(t)
				}
				processed++
			default:
				goto drained
			}
		}
	drained:
		_ = processed
		if m.sustained {
			now := time.Now()
			if m.lastSample.IsZero() || now.Sub(m.lastSample) >= time.Second {
				var ms runtime.MemStats
				runtime.ReadMemStats(&ms)
				m.lastSample = now
				m.samples = append(m.samples, statSample{T: now.Sub(m.start).Seconds(), Ticks: m.tickCount, TotalAlloc: ms.TotalAlloc, NumGC: ms.NumGC, PauseTotal: ms.PauseTotalNs, HeapAlloc: ms.HeapAlloc})
			}
			if now.Sub(m.start) >= m.duration {
				if m.doneCh != nil { select { case <-m.doneCh: default: close(m.doneCh) } }
				return m, tea.Quit
			}
		}
		return m, nextFrameCmd()
	case quitAfterDeadlineMsg:
		if m.doneCh != nil { select { case <-m.doneCh: default: close(m.doneCh) } }
		return m, tea.Quit
	}
	return m, nil
}

func sparkline(vals []float64) string {
	if len(vals) == 0 {
		return ""
	}
	glyphs := []rune("▁▂▃▄▅▆▇█")
	min, max := vals[0], vals[0]
	for _, v := range vals {
		if v < min {
			min = v
		}
		if v > max {
			max = v
		}
	}
	span := max - min
	if span == 0 {
		span = 1
	}
	var b strings.Builder
	for _, v := range vals {
		idx := int((v - min) / span * float64(len(glyphs)-1))
		b.WriteRune(glyphs[idx])
	}
	return b.String()
}

func gauge(label string, v float64, width int) string {
	filled := int(v * float64(width))
	bar := strings.Repeat("█", filled) + strings.Repeat("░", width-filled)
	return fmt.Sprintf("%-7s %s %3.0f%%", label, bar, v*100)
}

